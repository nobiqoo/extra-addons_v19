# -*- coding: utf-8 -*-

from odoo import api, fields, models

PURCHASE_CATEGORIES = [
    ('national', 'National'),
    ('import', 'Import'),
    ('dropship', 'Dropship'),
]


class PurchaseOrder(models.Model):
    _inherit = 'purchase.order'

    import_ids = fields.Many2many(
        comodel_name='purchase.import',
        relation='purchase_import_purchase_order_rel',
        column1='purchase_order_id',
        column2='purchase_import_id',
        string='Imports',
        copy=False,
        readonly=True,
    )
    purchase_category = fields.Selection(
        selection=PURCHASE_CATEGORIES,
        string='Purchase Type',
        compute='_compute_purchase_category',
        store=True,
        readonly=True,
        compute_sudo=True,
        index=True,
        help='Import: the order is linked to an import that is not cancelled.\n'
             'Dropship: the order was generated by Replenish on Order (MTO) from a sales order.\n'
             'National: any other purchase.',
    )

    @api.depends('import_ids.state', 'order_line.move_dest_ids.sale_line_id')
    def _compute_purchase_category(self):
        for order in self:
            if any(purchase_import.state != 'cancel' for purchase_import in order.import_ids):
                order.purchase_category = 'import'
            # Triangulación: alguna línea nació por MTO para un movimiento de una venta
            elif order.order_line.move_dest_ids.sale_line_id:
                order.purchase_category = 'dropship'
            else:
                order.purchase_category = 'national'
